<?php
/**
 * Custom WooCommerce thank-you template integration.
 *
 * @package StoreStackCheckoutForWooCommerce
 */

declare(strict_types=1);

namespace StoreStackCheckoutForWooCommerce;

defined( 'ABSPATH' ) || exit;


/**
 * Class ThankYou.
 *
 * Loads the custom order confirmation template.
 */
class ThankYou {

	/**
	 * Register 'Thank You' page filters and action hooks.
	 */
	public function __construct() {
		add_filter( 'template_include', array( $this, 'override_thankyou_template' ), 9999 );
		add_filter( 'woocommerce_locate_template', array( $this, 'override_thankyou_template_parts' ), 9999, 3 );
        add_action( 'wp_enqueue_scripts', array( $this, 'thankyou_enqueue_scripts' ), 9999 );
	}

	/**
	 * Select a custom 'Thank You' page template when viewing the order received page.
	 *
	 * @param string $template Original template path.
	 * @return string Selected template path.
	 */
	public function override_thankyou_template( string $template ): string {
		if ( ! is_order_received_page() ) {
			return $template;
		}

		/**
		 * Filters the override template for the 'Thank You' page.
		 *
		 * @since 1.0.0
		 *
		 * @param string $override_template The path to the override template.
		 * @param string $template The original template path.
		 */
		$override_template = apply_filters( 'storestack_thankyou_override_template', SSCFW_PLUGIN_PATH . 'templates/checkout.php', $template );

		return file_exists( $override_template ) ? $override_template : $template;
	}

	/**
	 * Select a custom WooCommerce template part for the 'Thank You' page.
	 *
	 * @param string $template      Original template path.
	 * @param string $template_name Template name relative to WooCommerce templates.
	 * @param string $template_path WooCommerce template directory.
	 * @return string Selected template path.
	 */
	public function override_thankyou_template_parts( string $template, string $template_name, string $template_path ): string {
		if ( ! is_order_received_page() || 'woocommerce/' !== $template_path ) {
			return $template;
		}

		/**
		 * Filters the override template part for the 'Thank You' page.
		 *
		 * @since 1.0.0
		 *
		 * @param string $override_template The path to the override template.
		 * @param string $template The original template path.
		 * @param string $template_name The name of the template.
		 * @param string $template_path The path to the template.
		 */
		$override_template = apply_filters(
			'storestack_thankyou_override_template_part',
			SSCFW_PLUGIN_PATH . 'templates/woocommerce/' . $template_name,
			$template,
			$template_name,
			$template_path
		);

		return file_exists( $override_template ) ? $override_template : $template;
	}

    /**
	 * Enqueue assets and remove conflicting theme styles for the 'Thank You' page.
	 */
	public function thankyou_enqueue_scripts(): void {
		if ( ! is_order_received_page() ) {
			return;
		}

		// Remove theme-related CSS styles (plugin/gateway styles are preserved).
		$wp_styles = wp_styles();

		foreach ( $wp_styles->queue as $handle ) {
			if ( ! isset( $wp_styles->registered[ $handle ] ) ) {
				continue;
			}

			$src = $wp_styles->registered[ $handle ]->src;

			// 1. Check if the source file is located in the themes directory (this includes both parent and child themes)
			if ( ! empty( $src ) && str_contains( $src, '/wp-content/themes/' ) ) {
				wp_dequeue_style( $handle );
			}

			// 2. Block themes: 'global-styles' is generated by WP core from theme.json / customizer
			if ( in_array( $handle, array( 'global-styles', 'wp-block-library-theme' ), true ) ) {
				wp_dequeue_style( $handle );
			}
		}

		// Dequeue WooCommerce Checkout Block styles and scripts.
		wp_dequeue_script( 'wc-checkout-block' );

		// Ensure the classic checkout scripts load so AJAX cart calculation
		// and third-party payment gateways still function correctly.
		wp_enqueue_script( 'wc-checkout' );

		// Enqueue our CSS styles.
		wp_enqueue_style( Checkout::STYLE_HANDLE, SSCFW_PLUGIN_URL . 'assets/css/frontend.css', array(), SSCFW_PLUGIN_VERSION );

		// Enqueue core checkout JS (dialog, coupon AJAX, Enter-key guard, mobile total sync).
		wp_enqueue_script(
			'storestack-checkout-bundle',
			SSCFW_PLUGIN_URL . 'assets/js/checkout.js',
			array( 'jquery' ),
			SSCFW_PLUGIN_VERSION,
			true
		);

		/**
		 * Fires after 'Thank You' scripts are enqueued.
		 *
		 * Allows developers to enqueue additional scripts or styles for the 'Thank You' page.
		 *
		 * @since 1.0.0
		 */
		do_action( 'storestack_thankyou_enqueue_scripts' );
	}
}
